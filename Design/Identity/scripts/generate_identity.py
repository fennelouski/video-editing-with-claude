#!/usr/bin/env python3
"""Generate Clauto's editable SVGs and native SwiftUI paths with stdlib only."""
from html import escape
import json
from pathlib import Path
import re

IDENTITY = Path(__file__).resolve().parents[1]
REPO = IDENTITY.parents[1]
DATA = json.loads((IDENTITY / "geometry.json").read_text())
PALETTE = DATA["palette"]


def path_element(d, *, fill="none", stroke="none", width=1.7):
    return (f'<path d="{d}" fill="{fill}" stroke="{stroke}" '
            f'stroke-width="{width}" stroke-linecap="square" stroke-linejoin="miter"/>')


def svg_document(title, content, *, viewbox="0 0 24 24"):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" '
            f'role="img" aria-labelledby="title description" style="color:{PALETTE["ink"]}">\n'
            f'  <title id="title">{escape(title)}</title>\n'
            '  <desc id="description">Original Clauto geometric artwork. Editable paths; '
            'source geometry.json; generated by scripts/generate_identity.py.</desc>\n'
            + content + '\n</svg>\n')


def icon_content(icon):
    lines = [path_element(d, stroke="currentColor", width=DATA["strokeWidth"])
             for d in icon.get("stroke", [])]
    lines += [path_element(d, fill="currentColor") for d in icon.get("fill", [])]
    return "\n".join(lines)


def emblem_content(*, tile=False, reversed=False):
    emblem = DATA["emblem"]
    paths = ([emblem["tile"]] if tile else []) + emblem["paths"]
    return "\n".join(path_element(item["d"], fill=(PALETTE["viridian"]
            if item["fill"] == "ivory" and not (tile or reversed)
            else PALETTE[item["fill"]])) for item in paths)


def swift_path(d, indentation):
    tokens = re.findall(r"[MLCQZ]|-?\d+(?:\.\d+)?", d)
    statements = []
    i = 0
    point = lambda x, y: f"CGPoint(x: {x}, y: {y})"
    while i < len(tokens):
        command = tokens[i]
        i += 1
        count = {"M": 2, "L": 2, "C": 6, "Q": 4, "Z": 0}[command]
        values = tokens[i:i + count]
        i += count
        if command == "M":
            statements.append(f"path.move(to: {point(*values)})")
        elif command == "L":
            statements.append(f"path.addLine(to: {point(*values)})")
        elif command == "Q":
            statements.append(f"path.addQuadCurve(to: {point(*values[2:])}, control: {point(*values[:2])})")
        elif command == "C":
            statements.append(f"path.addCurve(to: {point(*values[4:])}, control1: {point(*values[:2])}, control2: {point(*values[2:4])})")
        else:
            statements.append("path.closeSubpath()")
    return "\n".join(indentation + statement for statement in statements)


def generate_swift():
    cases = ", ".join(DATA["icons"])
    switches = []
    for name, icon in DATA["icons"].items():
        case = f"        case .{name}:\n"
        if icon.get("stroke"):
            case += "            if !filled {\n" + "\n".join(swift_path(d, "                ") for d in icon["stroke"]) + "\n            }\n"
        if icon.get("fill"):
            case += "            if filled {\n" + "\n".join(swift_path(d, "                ") for d in icon["fill"]) + "\n            }\n"
        switches.append(case.rstrip())
    source = '''// Original Clauto artwork. Generated from Design/Identity/geometry.json.
// Regenerate with: python3 Design/Identity/scripts/generate_identity.py
// No SF Symbols, third-party icon library, or runtime SVG parsing.
import SwiftUI

enum ClautoIconName: String, CaseIterable, Sendable {
    case CASES
}

/// An authored 24-unit icon. Supply the surrounding control's accessible label.
/// Inherits foregroundStyle; the stroke width is expressed in source-grid units.
struct ClautoIcon: View {
    let name: ClautoIconName
    var size: CGFloat
    var strokeWidth: CGFloat?
    init(_ name: ClautoIconName, size: CGFloat = 18, strokeWidth: CGFloat? = nil) {
        self.name = name;self.size = size;self.strokeWidth = strokeWidth
    }
    var body: some View {
        let palette = ClautoThemeStore.shared.palette,style = palette.geometry.icon
        let weight = (strokeWidth ?? CGFloat(palette.geometry.iconStroke))*size/24
        ZStack {
            if style == .badge {
                ClautoThemedShape(palette: palette).fill(ClautoDesign.citron.opacity(0.20))
                ClautoThemedShape(palette: palette).stroke(lineWidth: palette.geometry.stroke*0.6)
            }
            if style == .native {
                Image(systemName: nativeSymbol).font(.system(size: size*0.85,weight: .regular))
            } else {
                ZStack {
                    ClautoIconShape(name: name,filled: false).stroke(style: StrokeStyle(lineWidth: weight,
                        lineCap: style == .rounded || style == .badge ? .round:.square,
                        lineJoin: style == .rounded || style == .badge ? .round:.miter))
                    ClautoIconShape(name: name,filled: true).fill()
                }.padding(style == .badge ? size*0.18:style == .technical ? size*0.1:0)
                if style == .technical {
                    CutCorner(cut: size*0.2).stroke(style: StrokeStyle(lineWidth: weight*0.5,dash: [size*0.15,size*0.12]))
                }
            }
        }.frame(width: size,height: size).accessibilityHidden(true)
    }
    private var nativeSymbol: String {
        switch name {
        case .project,.folder: "folder"
        case .brief: "doc.text"
        case .files: "doc.on.doc"
        case .cut: "scissors"
        case .conversation: "text.bubble"
        case .add: "plus"
        case .open: "arrow.up.forward.square"
        case .play: "play.fill"
        case .pause: "pause.fill"
        case .seek: "forward.end"
        case .arrow: "arrow.right"
        case .science: "flask"
        case .font: "textformat"
        case .cutout: "person.crop.rectangle"
        case .audio: "waveform"
        case .export: "square.and.arrow.up"
        case .check: "checkmark"
        case .close: "xmark"
        case .settings: "slider.horizontal.3"
        case .version: "square.stack"
        }
    }
}

/// The exact editable SVG geometry, transformed into the view's local rectangle.
struct ClautoIconShape: Shape {
    let name: ClautoIconName
    var filled = false

    func path(in rect: CGRect) -> Path {
        var path = Path()
        switch name {
SWITCHES
        }
        return path.applying(CGAffineTransform(scaleX: rect.width / 24, y: rect.height / 24))
            .applying(CGAffineTransform(translationX: rect.minX, y: rect.minY))
    }
}

/// Clauto's cut bracket and revisable strip, for rail or welcome compositions.
/// Color each layer explicitly; the mark does not add a tile or a stock symbol.
struct ClautoEmblem: View {
    var bracketColor: Color
    var stripColor: Color

    var body: some View {
        ZStack {
            ClautoEmblemShape(strip: false).fill(bracketColor)
            ClautoEmblemShape(strip: true).fill(stripColor)
        }
        .aspectRatio(1, contentMode: .fit)
        .accessibilityHidden(true)
    }
}

private struct ClautoEmblemShape: Shape {
    let strip: Bool

    func path(in rect: CGRect) -> Path {
        var path = Path()
        if strip {
STRIP
        } else {
BRACKET
        }
        return path.applying(CGAffineTransform(scaleX: rect.width / 1024, y: rect.height / 1024))
            .applying(CGAffineTransform(translationX: rect.minX, y: rect.minY))
    }
}
'''.replace("CASES", cases).replace("SWITCHES", "\n".join(switches))
    source = source.replace("STRIP", swift_path(DATA["emblem"]["paths"][1]["d"], "            "))
    source = source.replace("BRACKET", swift_path(DATA["emblem"]["paths"][0]["d"], "            "))
    target = REPO / "Clauto Editor/Clauto Editor/Views/ClautoIcon.swift"
    target.write_text(source)


def generate_board():
    p = PALETTE
    content = [f'<rect width="1440" height="1110" fill="{p["ivory"]}"/>']
    text = lambda x, y, words, size=20, fill=p["ink"], weight=400: (
        f'<text x="{x}" y="{y}" fill="{fill}" font-family="Work Sans" '
        f'font-size="{size}" font-weight="{weight}">{escape(words)}</text>')
    content += [text(64, 96, "Clauto", 54, weight=600),
                text(65, 133, "The splice vocabulary", 22, p["muted"]),
                f'<g transform="translate(46 174) scale(0.3)">{emblem_content(tile=True)}</g>',
                text(416, 220, "An open cut bracket.", 28, weight=600),
                text(416, 260, "A strip that stays movable.", 28, weight=600),
                text(416, 311, "The mark joins Clauto’s initial with the act of revising a cut.", 20, p["muted"]),
                text(416, 348, "The diagonal seam carries into document corners and editing tools.", 20, p["muted"]),
                text(416, 385, "Pure geometry. No textures, stock artwork, or platform symbols.", 20, p["muted"])]
    for index, name in enumerate(["ink", "viridian", "ivory", "citron", "terracotta"]):
        x = 416 + index * 182
        content += [f'<rect x="{x}" y="424" width="136" height="32" fill="{p[name]}" stroke="{p["muted"]}" stroke-width="0.6"/>',
                    text(x, 480, name.capitalize(), 16), text(x, 503, p[name], 14, p["muted"])]
    content += [f'<rect x="64" y="541" width="1312" height="1" fill="{p["muted"]}"/>',
                text(64, 593, "Drawn to work at 16, 20, and 24 pixels", 28, weight=600),
                text(64, 627, "24-unit grid · 1.7-unit square stroke · editable SVG + SwiftUI paths", 18, p["muted"])]
    for index, (name, icon) in enumerate(DATA["icons"].items()):
        col, row = index % 7, index // 7
        x, y = 64 + col * 192, 670 + row * 142
        content += [f'<g transform="translate({x} {y}) scale(1.5)">{icon_content(icon)}</g>',
                    text(x, y + 67, icon["label"], 17),
                    f'<g transform="translate({x} {y + 85}) scale(0.6666667)">{icon_content(icon)}</g>',
                    f'<g transform="translate({x + 38} {y + 83}) scale(0.8333333)">{icon_content(icon)}</g>',
                    f'<g transform="translate({x + 82} {y + 81})">{icon_content(icon)}</g>']
    content.append(text(64, 1080, "Original Clauto artwork · Source and reproduction instructions: Design/Identity/PROVENANCE.md", 16, p["muted"]))
    (IDENTITY / "identity-board.svg").write_text(svg_document("Clauto design identity", "\n".join(content), viewbox="0 0 1440 1110"))


def main():
    for name, icon in DATA["icons"].items():
        (IDENTITY / "icons" / f"{name}.svg").write_text(svg_document(f"Clauto {icon['label']}", icon_content(icon)))
    for filename, tile, reversed in [("app-icon.svg", True, True), ("emblem.svg", False, False), ("emblem-reversed.svg", False, True)]:
        (IDENTITY / filename).write_text(svg_document("Clauto splice emblem", emblem_content(tile=tile, reversed=reversed), viewbox="0 0 1024 1024"))
    generate_swift()
    generate_board()
    print(f"Generated {len(DATA['icons'])} SVG icons, 3 emblem variants, identity board, and SwiftUI paths.")


if __name__ == "__main__":
    main()
